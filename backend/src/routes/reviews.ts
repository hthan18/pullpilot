router.post('/:id/publish', async (req: AuthRequest, res) => {
  const id = positiveInteger(req.params.id);
  if (!id) return res.status(400).json({ error: 'Invalid review ID' });
  try {
    const result = await pool.query(
      `SELECT rv.*, repo.full_name, u.access_token FROM reviews rv
       JOIN repositories repo ON repo.id = rv.repository_id JOIN users u ON u.id = repo.user_id
       WHERE rv.id = $1 AND repo.user_id = $2`, [id, req.userId]
    );
    if (!result.rows.length) return res.status(404).json({ error: 'Review not found' });
    const review = result.rows[0];
    if (review.status !== 'completed' || !review.analysis_result?.findings) return res.status(409).json({ error: 'Only completed structured reviews can be published' });
    if (review.github_comment_url) return res.json({ github_comment_url: review.github_comment_url, already_published: true });
    const response = await axios.post(
      `https://api.github.com/repos/${review.full_name}/issues/${review.pr_number}/comments`,
      { body: reviewMarkdown(review) },
      { headers: { Authorization: `Bearer ${decryptToken(review.access_token)}`, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' } }
    );
    await pool.query('UPDATE reviews SET github_comment_url = $1 WHERE id = $2', [response.data.html_url, id]);
    res.json({ github_comment_url: response.data.html_url });
  } catch (error: unknown) {
    const status = axios.isAxiosError(error) ? error.response?.status : undefined;
    console.error('Error publishing GitHub review:', error);
    if (status === 401 || status === 403) return res.status(403).json({ error: 'GitHub permission denied. Sign out and authorize PullPilot again to grant public repository access.' });
    res.status(500).json({ error: 'Failed to publish review to GitHub' });
  }
});

